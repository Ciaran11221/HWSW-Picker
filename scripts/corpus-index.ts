// Generates corpus/INDEX.md from corpus/families/*.json.
// Run with: npm run corpus:index
//
// renderIndex is pure (no file access) so tests can compare the committed
// INDEX.md with what it would produce, without writing anything.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFamily, type Family } from '@hwsw/core';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FAMILIES_DIR = path.join(ROOT, 'corpus', 'families');
export const INDEX_PATH = path.join(ROOT, 'corpus', 'INDEX.md');

/** Markdown index of families, sorted by id. Output uses LF line endings. */
export function renderIndex(families: readonly Family[]): string {
  const sorted = [...families].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const rows = sorted.map(
    (f) => `| ${f.id} | ${f.name} | ${f.kind} | ${f.members.join(', ')} | ${f.eol ?? '-'} |`,
  );
  return [
    '# Tag family index',
    '',
    'Generated by `npm run corpus:index` from `corpus/families/*.json`. Do not edit by hand.',
    '',
    `${families.length} families.`,
    '',
    '| id | name | kind | members | eol |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

/** Reads and validates every `*.json` family file. Throws naming the file on the first bad one. */
export function loadFamilies(dir: string = FAMILIES_DIR): Family[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => {
      try {
        return parseFamily(JSON.parse(readFileSync(path.join(dir, file), 'utf8')));
      } catch (err) {
        throw new Error(`${file}: ${(err as Error).message}`);
      }
    });
}

function isEntryPoint(): boolean {
  const entry = process.argv[1];
  if (entry === undefined) return false;
  const norm = (p: string) => path.resolve(p).toLowerCase();
  return norm(entry) === norm(fileURLToPath(import.meta.url));
}

if (isEntryPoint()) {
  const families = loadFamilies();
  writeFileSync(INDEX_PATH, renderIndex(families), 'utf8');
  console.log(`Wrote ${path.relative(ROOT, INDEX_PATH)} (${families.length} families)`);
}
